// Set page address 0~10
void Set_Page_Address(unsigned char add) {
  add = 0xb0 | add;
  Write_Instruction(add);
  return;
}

void Set_Column_Address(unsigned char add) {
  Write_Instruction((0x10 | (add >> 4)));
  Write_Instruction((0x0f & add));
  return;
}

